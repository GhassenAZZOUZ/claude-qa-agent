// Unit tests for plan-check.mjs. Run from the repo root: node --test scripts/plan-check.test.mjs
// Each case starts from the example plan (examples/test-plans/) in a temp qa-artifacts/ tree,
// changes one thing, and runs plan-check.mjs as a child process, as WAY 1/4/19 do.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const script = path.join(root, 'scripts/plan-check.mjs');
const example = fs.readFileSync(path.join(root, 'examples/test-plans/checkout-discount-2026-10-09.md'), 'utf8');

// Writes the plan (optionally edited) and the given test files; returns { status, out }
function check(edit = s => s, files = [], ...args) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'plan-check-'));
  const plan = path.join(dir, 'qa-artifacts/test-plans/plan.md');
  const folder = path.join(dir, 'qa-artifacts/test-cases/checkout-discount-2026-10-09');
  fs.mkdirSync(path.dirname(plan), { recursive: true });
  fs.mkdirSync(folder, { recursive: true });
  fs.writeFileSync(plan, edit(example));
  for (const f of files) fs.writeFileSync(path.join(folder, f), '');
  const r = spawnSync(process.execPath, [script, plan, ...args], { encoding: 'utf8' });
  fs.rmSync(dir, { recursive: true, force: true });
  return { status: r.status, out: r.stdout + r.stderr };
}
const replace = (from, to) => s => { assert.ok(s.includes(from), `example has no "${from}"`); return s.replace(from, to); };

test('the example plan passes', () => {
  const r = check();
  assert.equal(r.status, 0, r.out);
  assert.match(r.out, /5 planned tests, 4 requirements covered, 1 retired/);
});

test('a requirement with no planned test fails', () => {
  const r = check(replace('| AC-04 | P0 |', '| AC-01 | P0 |'));
  assert.equal(r.status, 1);
  assert.match(r.out, /AC-04 has no planned test/);
});

test('covering an unknown requirement fails', () => {
  const r = check(replace('| AC-04 | P0 |', '| AC-09 | P0 |'));
  assert.match(r.out, /covers AC-09, which is not in ## Requirements/);
});

test('a retired ID is never reused', () => {
  const r = check(replace('| Test#06 | Duplicate', '| Test#05 | Duplicate'));
  assert.equal(r.status, 1);
  assert.match(r.out, /Test#05 is both planned and retired/);
});

test('priority and its tag must match', () => {
  const r = check(replace('@medium @checkout-discount | AC-03 | P2 |', '@medium @checkout-discount | AC-03 | P0 |'));
  assert.match(r.out, /Test#04: P0 needs the @critical tag/);
});

test('level and project tag must match', () => {
  const r = check(replace('| boundary | ui | @e2e @boundary', '| boundary | api | @e2e @boundary'));
  assert.match(r.out, /Test#04: an api test is tagged @api/);
});

test('an unknown category or status fails', () => {
  const r = check(s => s.replace('| boundary | ui |', '| limits | ui |').replace('**Status:** approved', '**Status:** ok'));
  assert.match(r.out, /category "limits"/);
  assert.match(r.out, /\*\*Status:\*\* must be/);
});

test('a missing watermark fails', () => {
  const r = check(replace('🤖 _Generated by DevOps QA Agent — review before acting on this._', ''));
  assert.match(r.out, /watermark footer missing/);
});

test('an unexplained missing negative test is a warning, not an error', () => {
  const r = check(replace('| negative | ui | @e2e @negative @critical @checkout-discount | AC-04 |', '| edge_case | ui | @e2e @edge-case @critical @checkout-discount | AC-04 |'));
  assert.equal(r.status, 0, r.out);
  assert.match(r.out, /⚠ AC-04 has no negative test/);
});

test('drift: written files must match the plan', () => {
  const r = check(undefined, ['Test#01.feature', 'Test#02.feature', 'Test#03.feature', 'Test#04.feature', 'Test#06.feature', 'Test#07.feature']);
  assert.equal(r.status, 1);
  assert.match(r.out, /Test#05 is planned but .* has no Test#05\.feature/);
  assert.match(r.out, /Test#06\.feature exists but the plan retired Test#06/);
  assert.match(r.out, /Test#07\.feature is not in the plan/);
});

test('drift: exactly the planned files pass, and --plan-only skips the folder', () => {
  const all = ['01', '02', '03', '04', '05'].map(n => `Test#${n}.feature`);
  assert.equal(check(undefined, all).status, 0);
  assert.equal(check(undefined, ['Test#09.feature'], '--plan-only').status, 0);
});

// --against: the coverage floor a review (WAY 20) must keep when it applies removals
function against(edit) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'plan-against-'));
  const oldPlan = path.join(dir, 'old.md'), newPlan = path.join(dir, 'new.md');
  fs.writeFileSync(oldPlan, example);
  fs.writeFileSync(newPlan, edit(example));
  const r = spawnSync(process.execPath, [script, newPlan, '--plan-only', '--against', oldPlan], { encoding: 'utf8' });
  fs.rmSync(dir, { recursive: true, force: true });
  return { status: r.status, out: r.stdout + r.stderr };
}
const TEST05 = '| Test#05 | A second code is refused once one is applied | negative | ui | @e2e @negative @critical @checkout-discount | AC-04 | P0 |\n';

test('--against: retiring the only negative test of a requirement breaks the floor', () => {
  const r = against(s => s.replace(TEST05, '').replace('| Test#06 | Duplicate', '| Test#05 | Merged away |\n| Test#06 | Duplicate'));
  assert.equal(r.status, 1);
  assert.match(r.out, /coverage floor: AC-04 would lose its only negative test/);
  assert.match(r.out, /AC-04 has no planned test/);
});

test('--against: an ID that vanishes instead of moving to Retired fails', () => {
  const r = against(s => s.replace('| Test#06 | Duplicate of Test#03: same XSS payload class on the same field |\n', ''));
  assert.equal(r.status, 1);
  assert.match(r.out, /Test#06 disappeared/);
});

test('--against: retiring a redundant test and adding one keeps the floor', () => {
  const add = '| Test#07 | Code field rejects SQL injection | security | api | @api @security @negative @high | AC-03 | P1 |\n';
  const r = against(s => s
    .replace('| Test#03 | Code input rejects an XSS payload | security | ui | @e2e @security @negative @high @checkout-discount | AC-03 | P1 |\n', add)
    .replace('| Test#06 | Duplicate', '| Test#03 | Covered by Test#07 at the api level |\n| Test#06 | Duplicate'));
  assert.equal(r.status, 0, r.out);
});

// --estimate: medians from past runs, defaults otherwise, and the P0+P1 budget
test('--estimate: median of past runs, Outline rows by default, budget warning', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'plan-estimate-'));
  const plan = path.join(dir, 'qa-artifacts/test-plans/plan.md');
  fs.mkdirSync(path.dirname(plan), { recursive: true });
  fs.writeFileSync(plan, example);
  const spec = (id, ms) => ({ file: `.features-gen/e2e/test-cases/checkout-discount-2026-10-09/Test#${id}.feature.spec.js`, tests: [{ results: [{ duration: ms }] }] });
  for (const [run, ms] of [['r1', 30000], ['r2', 90000], ['r3', 40000]]) {
    fs.mkdirSync(path.join(dir, 'qa-artifacts/runs', run), { recursive: true });
    fs.writeFileSync(path.join(dir, 'qa-artifacts/runs', run, 'results.json'),
      JSON.stringify({ suites: [{ specs: [spec('01', ms), spec('02', 5000), { ...spec('02', 5000) }] }] }));
  }
  const r = spawnSync(process.execPath, [script, plan, '--plan-only', '--estimate', '--budget', '1'], { encoding: 'utf8' });
  fs.rmSync(dir, { recursive: true, force: true });
  assert.equal(r.status, 0, r.stdout + r.stderr);
  assert.match(r.stdout, /Test#01 P0 ui 40s \(median of 3 runs\)/);
  assert.match(r.stdout, /Test#02 P0 ui 10s \(median of 3 runs\)/);  // two Outline rows in one feature add up
  assert.match(r.stdout, /Test#04 P2 ui 1m20s \(default 20s × 4 rows\)/);
  assert.match(r.stdout, /P0\+P1 1m30s · all 2m50s · 2\/5 measured · budget 1m/);
  assert.match(r.stdout, /⚠ P0\+P1 tests are estimated at 1m30s, over the 1 min budget/);
});
