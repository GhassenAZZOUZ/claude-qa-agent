// Checks a test plan (format: .claude/skills/test-plan/SKILL.md) and, when its test folder
// exists, that the folder holds exactly the planned tests. Run by WAY 1/4/19:
//   node scripts/plan-check.mjs qa-artifacts/test-plans/<feature>-<date>.md [--folder <dir> | --plan-only]
// Exit 1 on errors (printed as "✗ …"); warnings ("⚠ …") don't fail.
import fs from 'fs';
import path from 'path';

const args = process.argv.slice(2);
const planPath = args.find(a => !a.startsWith('--'));
if (!planPath) { console.error('usage: plan-check.mjs <plan.md> [--folder <dir> | --plan-only]'); process.exit(2); }
const folderArg = args.includes('--folder') ? args[args.indexOf('--folder') + 1] : null;

const text = fs.readFileSync(planPath, 'utf8').replace(/\r\n/g, '\n');
const errors = [], warnings = [];

// Rows of the table under "## <heading>", as objects keyed by the header cells
function table(heading) {
  const m = text.match(new RegExp(`^## ${heading}\\s*$([\\s\\S]*?)(?=^## |^---\\s*$|(?![\\s\\S]))`, 'm'));
  if (!m) return null;
  const lines = m[1].split('\n').filter(l => l.trim().startsWith('|'));
  if (lines.length < 2) return [];
  const cells = l => l.trim().replace(/^\||\|$/g, '').split('|').map(c => c.trim());
  const head = cells(lines[0]);
  return lines.slice(2).map(cells).filter(r => r.some(c => c)).map(r => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ''])));
}

for (const h of ['Requirements', 'Planned tests', 'Coverage', 'Retired']) {
  if (table(h) === null) errors.push(`missing "## ${h}" section`);
}
const status = (text.match(/^\*\*Status:\*\*\s*([a-z-]+)/m) || [])[1];
if (!['draft', 'awaiting-approval', 'approved', 'auto-approved'].includes(status)) {
  errors.push(`**Status:** must be draft | awaiting-approval | approved | auto-approved (got "${status ?? 'none'}")`);
}
if (!text.includes('🤖 _Generated by DevOps QA Agent — review before acting on this._')) errors.push('watermark footer missing');

const reqs = table('Requirements') || [];
const tests = table('Planned tests') || [];
const retired = table('Retired') || [];
const ID = /^Test#\d{2}$/;
const CATEGORIES = ['happy_path', 'negative', 'edge_case', 'boundary', 'security', 'permissions', 'performance'];
const PRIO_TAG = { P0: '@critical', P1: '@high', P2: '@medium', P3: '@low' };
const reqIds = new Set(reqs.map(r => r.ID));
const seen = new Set();

for (const t of tests) {
  const id = t.Test;
  if (!ID.test(id)) { errors.push(`"${id}": IDs are Test#<nn>, two digits`); continue; }
  if (seen.has(id)) errors.push(`${id} is listed twice`);
  seen.add(id);
  if (!CATEGORIES.includes(t.Category)) errors.push(`${id}: category "${t.Category}" is not one of ${CATEGORIES.join(', ')}`);
  if (!['ui', 'api'].includes(t.Level)) errors.push(`${id}: level "${t.Level}" must be ui or api`);
  const tags = t.Tags.split(/\s+/);
  if (t.Level === 'ui' && (!tags.includes('@e2e') || tags.includes('@api'))) errors.push(`${id}: a ui test is tagged @e2e and never @api`);
  if (t.Level === 'api' && !tags.includes('@api')) errors.push(`${id}: an api test is tagged @api`);
  if (!PRIO_TAG[t.Priority]) errors.push(`${id}: priority "${t.Priority}" must be P0–P3`);
  else if (!tags.includes(PRIO_TAG[t.Priority])) errors.push(`${id}: ${t.Priority} needs the ${PRIO_TAG[t.Priority]} tag`);
  const covers = t.Covers.split(/[,\s]+/).filter(Boolean);
  if (!covers.length) errors.push(`${id}: Covers is empty (use "untraced")`);
  for (const c of covers) if (c !== 'untraced' && !reqIds.has(c)) errors.push(`${id}: covers ${c}, which is not in ## Requirements`);
  if (covers.includes('untraced')) warnings.push(`${id} is untraced: it tests something no requirement states`);
}
for (const r of retired) {
  if (seen.has(r.Test)) errors.push(`${r.Test} is both planned and retired: retired IDs are never reused`);
}

// Coverage floor: every requirement has a test (error). A missing positive or negative one is a warning:
// a requirement that is itself a rejection ("expired code is rejected") has its negative test as its main flow
// A Coverage cell like "— (the rejection is the main flow)" records why a gap is intended
const NEG = ['negative', 'security', 'permissions'];
const coverage = Object.fromEntries((table('Coverage') || []).map(c => [c.Requirement, c]));
const explained = (r, col) => /^—\s*\(.+\)/.test(coverage[r.ID]?.[col] ?? '');
for (const r of reqs) {
  const mine = tests.filter(t => t.Covers.split(/[,\s]+/).includes(r.ID));
  if (!mine.length) { errors.push(`${r.ID} has no planned test`); continue; }
  if (!coverage[r.ID]) warnings.push(`${r.ID} has no line in ## Coverage`);
  if (!mine.some(t => t.Category === 'happy_path') && !explained(r, 'Positive')) warnings.push(`${r.ID} has no happy_path test: fine only when the requirement is itself a rejection (say so in ## Coverage)`);
  if (!mine.some(t => NEG.includes(t.Category)) && !explained(r, 'Negative')) warnings.push(`${r.ID} has no negative test: required when it takes input or an action (requirements-analysis §4)`);
}

// Drift: the test folder holds exactly the planned IDs (only once tests were written)
const folderLine = (text.match(/^\*\*Test folder:\*\*\s*(\S+)/m) || [])[1];
const folder = folderArg || (folderLine && path.join(path.dirname(planPath), '..', folderLine));
if (folder && !args.includes('--plan-only') && fs.existsSync(folder)) {
  const written = new Set(fs.readdirSync(folder).map(f => (f.match(/^(Test#\d{2})\.feature$/) || [])[1]).filter(Boolean));
  if (written.size) {
    for (const id of seen) if (!written.has(id)) errors.push(`${id} is planned but ${folder} has no ${id}.feature`);
    for (const id of written) {
      if (retired.some(r => r.Test === id)) errors.push(`${id}.feature exists but the plan retired ${id}: remove it with the user's OK`);
      else if (!seen.has(id)) errors.push(`${id}.feature is not in the plan: add it to the plan or remove it`);
    }
  }
}

warnings.forEach(w => console.log('⚠ ' + w));
errors.forEach(e => console.log('✗ ' + e));
if (errors.length) process.exit(1);
console.log(`✅ ${tests.length} planned tests, ${reqs.length} requirements covered, ${retired.length} retired`);
